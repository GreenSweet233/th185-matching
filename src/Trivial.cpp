// ---------------------------------------------------------------------------
// 形状 G：12 字节聚合拷贝（`movq` + `mov`）
//
// 3 个：0x00405830 / 0x00417730 / 0x00441650。
//
// ★ 这是线性代码，没有循环。
//   我第一版写成 `for (i=0;i<12;++i) dst[i]=src[i];`，
