//   编译器即使展开，源码结构仍与二进制不对齐。改成整体赋值。
// ---------------------------------------------------------------------------
//@witness func=0x00405830+0x00417730+0x00441650 kind=thiscall
void ObjVec3::copy_from(const Vec3Raw* source) { f_00 = *source; }

