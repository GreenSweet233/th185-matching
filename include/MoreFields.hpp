/**
 * 第 4 批匹配：字段写入器 / 聚合拷贝 / 位操作 / 全局访问。
 *
 * ## 本批的挑选标准
 *
 * 全部是**已有形状族的新实例**或极简单的新形状，不做需要新推理的复杂函数：
 *
 * | 形状 | 已被证明的样例 | 本批新增 |
 * |---|---|---:|
 * | 带帧 thiscall 写入器 `mov [ecx+N],eax / ret 4` | `0x00409F60` FieldAccess.cpp | 3 |
 * | 12 字节聚合拷贝 `movq`+`mov` | `0x004063C0` FieldAccess.cpp | 6 |
 * | 从指针取值写入 `mov eax,[ebp+8]; mov eax,[eax]; mov [ecx+N],eax` | 新形状 | 4 |
 * | 数组元素写入 `mov [ecx+eax*4+N],edx` | 新形状 | 1 |
 * | 位掩码 `sete` | `0x00407E40` FieldAccess.cpp | 2 |
 * | 8 字节聚合 / 全局对象整体拷贝 | 新形状 | 3 |
 * | 其余单形状实例（自增 / 位翻转 / SSE 双写 / 指针推进 / 全局链 / 表索引） | 各 1 | 7 |
 *
 * ## 命名纪律
 *
 * 结构体名一律 `ObjFwNN` / `ObjVecNN` / `ObjPtrNN` …，只表达「这个字段在 +NN」，
 * **不编造语义**。与 Object.hpp / FieldWriter.hpp 的约定一致：
 * 只声明有二进制见证的字段，字段之间用 `gap_XX_YY` 占位并注明未解析。
 */

#include <xmmintrin.h>

// ---------------------------------------------------------------------------
// 聚合类型（全局作用域）
//
// ★ 为什么放在 th185 命名空间**之外**：
//   check_bytes.py 会把 hpp 里的 `extern ...;` 行原样提到翻译单元最前面，
//   提出来的声明落在全局作用域。若这些类型只在 namespace 内可见，
//   相应 extern 就无法解析（C2065）。所以被 extern 引用的类型必须是全局的。
// ---------------------------------------------------------------------------

/// 12 字节聚合：3 个 int32。布局来自 `movq`(8 字节) + `mov`(4 字节) 的分割。
struct Triple32 {
    int x;
    int y;
    int z;
};

/// 8 字节聚合：2 个 int32。布局来自 `mov eax,[esi]` / `mov edx,[esi+4]` 的分割。
struct Pair32 {
    int a;
    int b;
};

