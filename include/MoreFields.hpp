// ---------------------------------------------------------------------------
// 位翻转：f = (f & ~1) | (arg & 1)
//
// 0x00433B70 原始机器码：
//   8b4118 (mov eax,[ecx+0x18])  334508 (xor eax,[ebp+8])
//   83e001 (and eax,1)           314118 (xor [ecx+0x18],eax)
//
// ★ 必须写成「先算位值再异或」。写成 if/else 两条分支会得到 cmov 序列
//   （`8bd6 83ce01 83e0fe 80e201 0f44f0`），字节完全不同 —— 实测过。
// ---------------------------------------------------------------------------
/// +0x18。0x00433B70。
struct ObjToggle18 {
    char gap_00_18[0x18];  ///< +0x00..+0x18 未解析（无证据的区间）
    unsigned f_18;         ///< +0x18，见证 0x00433B70

    void set_low_bit(int flip);
};

