// ---------------------------------------------------------------------------
// 位掩码判定：mov ecx,[ecx+N] / xor eax,eax / and cl,MASK / cmp cl,V / sete al
//
// ★ 返回 int 而非 bool —— 只有 int 才生成 `xor eax,eax` + `sete al`。
//   判据同 0x00407E40（FieldAccess.hpp 的 ObjField2A0::is_set）。
// ---------------------------------------------------------------------------
