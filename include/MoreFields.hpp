// ---------------------------------------------------------------------------
// 一次写两个相邻 float（xmm1 / xmm2）
//
// 与 Misc.cpp 的 ObjSse484C::store_both 同形，偏移不同。
// ★ 需要两个哑的 __m128 形参，值才能落在 xmm1 / xmm2（第 1 个 __m128 占 xmm0）。
// ---------------------------------------------------------------------------
/// +0xC4 / +0xC8。0x00433C60（`f30f1189c4000000 f30f1191c8000000 c3`）。
struct ObjSseC4C8 {
    char gap_00_C4[0xC4];  ///< +0x00..+0xC4 未解析（无证据的区间）
    float f_C4;            ///< +0xC4，见证 0x00433C60（xmm1）
    float f_C8;            ///< +0xC8，见证 0x00433C60（xmm2）

    void store(__m128, __m128 first, __m128 second);
};

// ---------------------------------------------------------------------------
// 指针推进 + 置标志
//   mov eax,[ecx+8]; cmp word [eax],'*'; jne L;
//   add eax,2; mov byte [ecx+0x18],1; mov [ecx+8],eax; L: ret
// ---------------------------------------------------------------------------
/// 0x0049C51C。20 字节。
///
/// `cmp word ptr [eax],0x2A` 比较的是 UTF-16 的 `*`，指针步进 2 字节，
/// 所以 +0x08 是「UTF-16 扫描指针」。**这只是形状推论**，字段语义未独立证实，
/// 故其余字段名保持中性。
struct ObjScan {
    char gap_00_08[0x08];  ///< +0x00..+0x08 未解析（无证据的区间）
    const short* p_08;     ///< +0x08，见证 0x0049C51C（`mov eax,[ecx+8]` + `add eax,2`）
    char gap_0C_18[0x0C];  ///< +0x0C..+0x18 未解析（无证据的区间）
    char f_18;             ///< +0x18，见证 0x0049C51C（`mov byte [ecx+0x18],1`）

    void skip_star();
};

// ---------------------------------------------------------------------------
